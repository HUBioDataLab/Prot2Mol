"""Curate the shared-molecule search into a candidate list for the cross-protein
ranking test, and show the ground-truth orderings for a worked example."""
from __future__ import annotations
import json, os
import numpy as np, pandas as pd
from scipy.stats import spearmanr
from itertools import combinations

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = "/home/furkan/Prot2Mol_Project/Prot2Mol"
SPLITS = {"scaffold": f"{ROOT}/dataset/processed/chembl_37/scaffold_component_split_median",
          "random":   f"{ROOT}/dataset/processed/chembl_37/target_aware_random_assay_activity_balanced_median"}
COLS = ["assay_group_id","target_chembl_id","protein_accession","molecule_chembl_id","pchembl_value"]

def load(split, part):
    return pd.read_parquet(f"{SPLITS[split]}/{part}.parquet", columns=COLS)

def orderings(df, assay, mols):
    g = df[(df.assay_group_id == assay) & (df.molecule_chembl_id.isin(mols))]
    g = g.groupby("molecule_chembl_id").pchembl_value.median()
    return g.reindex(sorted(mols))

L = []; A = L.append
A("# Candidate protein groups for the cross-protein ranking test")
A("")
A("Generated by `find_shared_molecule_groups.py` + `make_candidates_report.py`.")
A("")
A("## The test these candidates enable")
A("")
A("Take a molecule set that TWO different proteins have each really been measured")
A("against, where the two measured orderings disagree. Give the model the set with")
A("protein A, then the identical set with protein B. The molecules are fixed, so a")
A("protein-blind model can only emit one ordering and must fail at least one of the")
A("two ground truths. A target-conditioned model should track whichever protein it")
A("was given.")
A("")
A("This is strictly sharper than a decoy-protein swap: both proteins are real, both")
A("orderings are real, and the failure mode is directly observable rather than")
A("inferred from a correlation drop.")
A("")
A("## Selection criteria")
A("")
A("| criterion | value | why |")
A("|---|---|---|")
A("| different targets | required | otherwise there is nothing to discriminate |")
A("| same split part | required | A and B must both be train, or both val |")
A("| shared molecules | >= 6 | your floor; most candidates have far more |")
A("| pChEMBL span, each protein | >= 1.0 | each protein needs a real ordering, not noise |")
A("| `gt_spearman` | <= 0.2 | **the key filter** — the two ground truths must disagree |")
A("")
A("`gt_spearman` is Spearman between the two proteins' measured orderings of the")
A("shared molecules. At +1 the proteins rank identically and the test cannot")
A("discriminate no matter how many molecules are shared. Near 0 or negative is what")
A("makes the experiment decisive.")
A("")
A("## Feasibility — all four cells are usable")
A("")
A("| split | part | pairs with >=6 shared | of those, `gt_rho` <= 0.5 | **practical** | distinct targets |")
A("|---|---|---|---|---|---|")
summary = {}
prac = {}
for split in SPLITS:
    for part in ("train","val"):
        tag = f"{split}_{part}"
        d = pd.read_csv(os.path.join(HERE, f"shared_pairs_{tag}.csv"))
        p = d[(d.n_common.between(6,40)) & (d.gt_spearman <= 0.2) &
              (d.span_a >= 1.0) & (d.span_b >= 1.0)]
        prac[tag] = p
        summary[tag] = (len(d), int((d.gt_spearman<=0.5).sum()), len(p),
                        len(set(p.target_a)|set(p.target_b)))
        A(f"| {split} | {part} | {len(d):,} | {int((d.gt_spearman<=0.5).sum()):,} | "
          f"**{len(p):,}** | {len(set(p.target_a)|set(p.target_b)):,} |")
A("")
A("'Practical' = 6-40 shared molecules, `gt_rho` <= 0.2, both spans >= 1.0 — i.e. a set")
A("small enough to inspect by hand and a disagreement large enough to be decisive.")
A("")

for split in SPLITS:
    for part in ("train","val"):
        tag = f"{split}_{part}"
        p = prac[tag].copy()
        if p.empty: continue
        p["score"] = p.gt_spearman - 0.01*p.n_common      # prefer disagreement, then size
        top = p.sort_values("score").head(10)
        A(f"### {split} / {part} — top 10 pairs")
        A("")
        A("| target A | target B | shared mols | `gt_spearman` | span A | span B |")
        A("|---|---|---|---|---|---|")
        for r in top.itertuples():
            A(f"| `{r.target_a}` | `{r.target_b}` | {r.n_common} | **{r.gt_spearman:+.3f}** | "
              f"{r.span_a:.2f} | {r.span_b:.2f} |")
        A("")

# ---- multi-protein groups -------------------------------------------------
G = json.load(open(os.path.join(HERE, "shared_groups.json")))
A("## Multi-protein groups (3+ targets over one molecule set)")
A("")
A("Pairwise `gt_spearman` within each group is shown so you can see the")
A("disagreement is not driven by a single odd member.")
A("")
for tag, v in G.items():
    gs = [x for x in v.get("groups", []) if x.get("n_targets", 0) >= 3]
    if not gs: continue
    split, part = tag.split("_")
    df = load(split, part)
    seen = set(); shown = 0
    A(f"### {split} / {part}")
    A("")
    for x in sorted(gs, key=lambda z: (-z["n_targets"], -z["n_molecules"])):
        key = tuple(sorted(x["targets"]))
        if key in seen: continue
        seen.add(key)
        mols = x["molecules"]
        rhos = []
        for a, b in combinations(x["assays"], 2):
            ya, yb = orderings(df, a, mols), orderings(df, b, mols)
            ok = ya.notna() & yb.notna()
            if ok.sum() >= 3 and ya[ok].nunique() > 1 and yb[ok].nunique() > 1:
                r = spearmanr(ya[ok], yb[ok]).statistic
                if np.isfinite(r): rhos.append(r)
        if not rhos: continue
        A(f"- **{x['n_targets']} targets x {x['n_molecules']} shared molecules** — "
          f"{', '.join('`'+t+'`' for t in x['targets'])}  \n"
          f"  pairwise `gt_spearman`: min {min(rhos):+.3f}, median {np.median(rhos):+.3f}, max {max(rhos):+.3f}")
        shown += 1
        if shown >= 4: break
    A("")

# ---- worked example -------------------------------------------------------
A("## Worked example")
A("")
tag = "scaffold_val"
p = prac[tag]
cand = p[(p.n_common.between(7,12))].sort_values("gt_spearman").head(1)
if len(cand):
    r = cand.iloc[0]
    df = load("scaffold","val")
    ma = set(df[df.assay_group_id==r.assay_a].molecule_chembl_id)
    mb = set(df[df.assay_group_id==r.assay_b].molecule_chembl_id)
    mols = sorted(ma & mb)
    ya, yb = orderings(df, r.assay_a, mols), orderings(df, r.assay_b, mols)
    acc = df.drop_duplicates("target_chembl_id").set_index("target_chembl_id").protein_accession
    A(f"`{r.target_a}` ({acc.get(r.target_a,'?')}) and `{r.target_b}` ({acc.get(r.target_b,'?')}) "
      f"in the **scaffold validation** split share **{len(mols)} molecules**, "
      f"with `gt_spearman` = **{r.gt_spearman:+.3f}**.")
    A("")
    A("| molecule | pChEMBL vs A | rank A | pChEMBL vs B | rank B |")
    A("|---|---|---|---|---|")
    ra = ya.rank(ascending=False); rb = yb.rank(ascending=False)
    for m in sorted(mols, key=lambda z: -ya[z]):
        A(f"| `{m}` | {ya[m]:.2f} | {ra[m]:.0f} | {yb[m]:.2f} | {rb[m]:.0f} |")
    A("")
    A(f"- ordering under **A**: {' > '.join(ya.sort_values(ascending=False).index)}")
    A(f"- ordering under **B**: {' > '.join(yb.sort_values(ascending=False).index)}")
    A("")
    A("Same molecules, two real and largely opposite orderings. A model that emits one")
    A("ordering regardless of the protein can match at most one of these rows.")
    A("")

A("## Caveats")
A("")
A("- `gt_spearman` is computed on **median-aggregated** pChEMBL per (assay, molecule),")
A("  so it inherits that aggregation. Measurement noise alone is ~0.25 log units, so a")
A("  disagreement smaller than the span is not necessarily biological.")
A("- Some very large shared sets (hundreds to 10,163 molecules) come from screening")
A("  campaigns (Potency/qHTS) run against several targets. They are legitimate but")
A("  noisier per molecule; the 6-40 band avoids them.")
A("- Two targets sharing molecules are often homologues (same family, panel-screened).")
A("  That is what makes the test fair rather than trivial: a model keying on gross")
A("  sequence features will not separate them, which is the point.")
A("- All candidates here are **within one split part**, as required.")
A("")
open(os.path.join(HERE, "CANDIDATES.md"), "w").write("\n".join(L) + "\n")
print("wrote CANDIDATES.md")
