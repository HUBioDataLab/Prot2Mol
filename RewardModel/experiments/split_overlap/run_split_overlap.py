"""Entity overlap between train / val / test for each ChEMBL-37 reward-model split.

Two different proportions are reported for every pair, because they answer
different questions and can differ substantially:

  unique-entity basis   |A and B| / |distinct entities in B|
        "what share of the DISTINCT proteins (or molecules) appearing in B also
         appear in A?"  Every entity counts once, however often it is measured.

  row basis             share of B's ROWS whose entity appears in A
        "what share of B's MEASUREMENTS involve an entity also seen in A?"
         Weights each entity by how many times it was measured, so it reflects
         what a model actually sees during an epoch.

Both are directional: |A and B|/|A| is not |A and B|/|B|. A -> B always means
"measured against B", i.e. the denominator is B.

Proteins are keyed two ways (ChEMBL target id, and exact sequence string) because
one target id can carry a sequence shared with another. Molecules are keyed by
ChEMBL id, by raw SMILES, and - optionally, with --with-structure - by canonical
SMILES and Bemis-Murcko scaffold.
"""
from __future__ import annotations
import argparse, os
import numpy as np, pandas as pd

ROOT = "/home/furkan/Prot2Mol_Project/Prot2Mol"
SPLITS = {
    "scaffold": f"{ROOT}/dataset/processed/chembl_37/scaffold_component_split_median",
    "random":   f"{ROOT}/dataset/processed/chembl_37/target_aware_random_assay_activity_balanced_median",
}
PAIRS = [("train","val"),("val","train"),("train","test"),("test","train"),("val","test"),("test","val")]
PARTS = ("train","val","test")


def overlap_rows(frames, col):
    sets = {k: set(frames[k][col].dropna()) for k in PARTS}
    out = []
    for a, b in PAIRS:
        inter = sets[a] & sets[b]
        out.append(dict(pair=f"{a} -> {b}", inter=len(inter),
                        uniq=len(inter)/len(sets[b])*100 if sets[b] else float("nan"),
                        rows=frames[b][col].isin(sets[a]).mean()*100 if len(frames[b]) else float("nan"),
                        b_only=len(sets[b]-sets[a])))
    return sets, out


def table(md, sets, rows, caption):
    md.append(f"**{caption}** — distinct: "
              + ", ".join(f"{k} {len(sets[k]):,}" for k in PARTS))
    md.append("")
    md.append("| pair (A → B) | &#124;A ∩ B&#124; | unique-entity basis | row basis | entities only in B |")
    md.append("|---|---|---|---|---|")
    for r in rows:
        md.append(f"| {r['pair']} | {r['inter']:,} | {r['uniq']:.2f}% | {r['rows']:.2f}% | {r['b_only']:,} |")
    md.append("")


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--with-structure", action="store_true",
                    help="also key molecules by canonical SMILES and Murcko scaffold (needs rdkit, slower)")
    ap.add_argument("--structure-sample", type=int, default=40000)
    ap.add_argument("--out", default=os.path.join(os.path.dirname(os.path.abspath(__file__)),
                                                  "SPLIT_OVERLAP.md"))
    args = ap.parse_args()

    cols = ["target_chembl_id","protein_sequence","molecule_chembl_id","smiles"]
    md = ["# Train / val / test overlap in the reward-model splits", "",
          "Generated by `run_split_overlap.py`.", "", "## Method", ""]
    md += [l for l in __doc__.strip().split("\n")[2:]]
    md += ["", "## Dataset sizes", "", "| split | train rows | val rows | test rows |", "|---|---|---|---|"]

    data = {}
    for s, p in SPLITS.items():
        data[s] = {k: pd.read_parquet(f"{p}/{k}.parquet", columns=cols) for k in PARTS}
        md.append(f"| {s} | {len(data[s]['train']):,} | {len(data[s]['val']):,} | {len(data[s]['test']):,} |")
    md.append("")

    for s in SPLITS:
        md.append(f"## {s} split")
        md.append("")
        md.append("### Proteins")
        md.append("")
        for col, cap in (("target_chembl_id","Keyed by ChEMBL target id"),
                         ("protein_sequence","Keyed by exact sequence string")):
            sets, rows = overlap_rows(data[s], col)
            table(md, sets, rows, cap)
        md.append("### Molecules")
        md.append("")
        for col, cap in (("molecule_chembl_id","Keyed by ChEMBL molecule id"),
                         ("smiles","Keyed by raw SMILES string")):
            sets, rows = overlap_rows(data[s], col)
            table(md, sets, rows, cap)

        if args.with_structure:
            from rdkit import Chem, RDLogger
            from rdkit.Chem.Scaffolds import MurckoScaffold
            RDLogger.DisableLog("rdApp.*")
            rng = np.random.default_rng(0)
            uni = {k: sorted(set(data[s][k].smiles.dropna())) for k in PARTS}
            samp = {k: rng.choice(uni[k], size=min(args.structure_sample, len(uni[k])), replace=False)
                    for k in PARTS}
            canon, scaf = {}, {}
            for k in PARTS:
                c, sc = set(), set()
                for x in samp[k]:
                    m = Chem.MolFromSmiles(x)
                    if m is None: continue
                    c.add(Chem.MolToSmiles(m))
                    try: sc.add(MurckoScaffold.MurckoScaffoldSmiles(mol=m))
                    except Exception: pass
                canon[k], scaf[k] = c, sc
            md.append(f"**Structural keys** — computed on a random sample of "
                      f"{args.structure_sample:,} distinct SMILES per part.")
            md.append("")
            md.append("> A sampled intersection UNDER-counts whenever the true overlap is non-zero, "
                      "because two independent samples need not draw the same shared entity. "
                      "A sampled intersection of exactly **0** is still conclusive. Use the "
                      "full-population rows above for non-zero overlaps.")
            md.append("")
            md.append("| key | pair | &#124;A ∩ B&#124; | % of B's sampled set |")
            md.append("|---|---|---|---|")
            for name, dd in (("canonical SMILES", canon), ("Murcko scaffold", scaf)):
                for a, b in [("train","val"),("train","test"),("val","test")]:
                    i = dd[a] & dd[b]
                    md.append(f"| {name} | {a} → {b} | {len(i):,} | {len(i)/max(len(dd[b]),1)*100:.2f}% |")
            md.append("")

    with open(args.out, "w") as f:
        f.write("\n".join(md) + "\n")
    print(f"wrote {args.out}")


if __name__ == "__main__":
    main()
